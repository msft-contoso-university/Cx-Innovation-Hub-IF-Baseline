"""
Scenario: Task Lifecycle (Write Path)

Simulates a user creating a project, adding a task to it, editing the task,
reassigning it, and finally deleting it.  Covers the write endpoints that the
read-oriented scenarios never exercise.
Thresholds: POST/PUT/PATCH/DELETE p95 < 1000 ms.
"""

import random

from locust import task

try:
    from .base import TaskifyBaseUser
except ImportError:
    from base import TaskifyBaseUser

WRITE_THRESHOLD_MS = 1000

TASK_TITLES = [
    "Investigate flaky pipeline",
    "Refactor board column rendering",
    "Add retry to database connection",
    "Document deployment runbook",
    "Tune Postgres connection pool",
]


class TaskLifecycleUser(TaskifyBaseUser):
    """User that exercises the full create/update/assign/delete task flow."""

    weight = 2

    def _check_write(self, resp, label):
        """Fail the sample on non-2xx status or a breached latency threshold."""
        if resp.status_code < 200 or resp.status_code >= 300:
            resp.failure(f"{label}: status {resp.status_code}")
            return False
        if resp.elapsed.total_seconds() * 1000 > WRITE_THRESHOLD_MS:
            resp.failure(
                f"{label}: response time {resp.elapsed.total_seconds()*1000:.0f}ms > {WRITE_THRESHOLD_MS}ms"
            )
            return False
        return True

    @task
    def task_lifecycle(self):
        """Create a project and run a task through create → update → assign → delete."""
        # Create a dedicated project so concurrent users never share task state
        with self.client.post(
            "/api/projects",
            json={
                "name": f"Perf Project {random.randint(1, 1_000_000)}",
                "description": "Created by the task lifecycle performance scenario",
            },
            name="POST /api/projects",
            catch_response=True,
        ) as resp:
            if not self._check_write(resp, "task_lifecycle create project"):
                return
            project = resp.json()

        project_id = project.get("id", project.get("_id"))
        if project_id is None:
            return

        # Create a task in the new project
        with self.client.post(
            f"/api/projects/{project_id}/tasks",
            json={
                "title": random.choice(TASK_TITLES),
                "description": "Generated by the task lifecycle performance scenario",
            },
            name="POST /api/projects/:projectId/tasks",
            catch_response=True,
        ) as resp:
            if not self._check_write(resp, "task_lifecycle create task"):
                return
            created_task = resp.json()

        task_id = created_task.get("id", created_task.get("_id"))
        if task_id is None:
            return

        # Edit the task title/description
        with self.client.put(
            f"/api/tasks/{task_id}",
            json={
                "title": f"{created_task.get('title', 'Task')} (updated)",
                "description": "Updated by the task lifecycle performance scenario",
            },
            name="PUT /api/tasks/:id",
            catch_response=True,
        ) as resp:
            self._check_write(resp, "task_lifecycle update task")

        # Assign a user (or unassign when no seed users were loaded)
        assigned_user_id = None
        if self.users:
            assignee = random.choice(self.users)
            assigned_user_id = assignee.get("id", assignee.get("_id"))

        with self.client.patch(
            f"/api/tasks/{task_id}/assign",
            json={"assigned_user_id": assigned_user_id},
            name="PATCH /api/tasks/:id/assign",
            catch_response=True,
        ) as resp:
            self._check_write(resp, "task_lifecycle assign task")

        # Clean up so repeated iterations do not grow the dataset unboundedly
        with self.client.delete(
            f"/api/tasks/{task_id}",
            name="DELETE /api/tasks/:id",
            catch_response=True,
        ) as resp:
            self._check_write(resp, "task_lifecycle delete task")
